// IEEE 1800-2023 §§6.22.1, 10.3.2, 10.9.1, 10.9.2.
`timescale 1ns/1ps
module top;
  typedef struct packed {logic [3:0] a,b;} P;
  typedef P Alias1;
  typedef Alias1 Alias2;
  typedef struct {int tag; P pk;} S;
  typedef struct packed {logic [3:0] c,d;} Q;
  typedef logic [3:0] N4;
  typedef logic [7:0] V;
  typedef struct {int tag; V pk;} SV;
  typedef P [1:0] PA;
  typedef struct {int tag; PA pk;} SPA;
  typedef enum logic [7:0] {E12=8'h12,E34=8'h34} E;
  typedef struct {int tag; E pk;} SE;
  typedef struct {int tag; P x,y;} SM;
  typedef struct {int tag; S sub;} SN;
  typedef logic [1:0][3:0] M;
  typedef logic [0:1][3:0] MR;
  typedef struct {int tag;M pk;} MS;
  M m;
  MR mr;
  MS matrix_s,matrix_different;
  P p;
  Alias2 alias_p;
  Q q;
  V v;
  PA pa;
  E e;
  S s, alias_s, different, typed, named, leaf_key;
  SV vs;
  SPA pas;
  SE es;
  SM many;
  SN nested;
  P arr[2];
  assign matrix_s='{tag:7,default:m};
  assign matrix_different='{tag:7,default:mr};
  assign s='{tag:7,default:p};
  assign alias_s='{tag:7,default:alias_p};
  assign different='{tag:7,default:q};
  assign typed='{int:9,default:p};
  assign leaf_key='{N4:4'h9,default:p};
  assign named='{pk:8'h56,default:p};
  assign vs='{tag:7,default:v};
  assign pas='{tag:7,default:pa};
  assign es='{tag:7,default:e};
  assign many='{tag:7,default:p};
  assign nested='{tag:7,sub:'{int:9,default:p}};
  assign arr='{default:p};
  initial begin
    m=8'h12;
    mr=8'h56;
    p=8'h12;
    alias_p=8'h34;
    q=8'h56;
    v=8'h9a;
    pa=16'h1234;
    e=E12;
    #1;
    $display("T|multidim %0d %h %h",matrix_s.tag,matrix_s.pk[1],matrix_s.pk[0]);
    $display("T|multidim_different %0d %h %h",matrix_different.tag,matrix_different.pk[1],matrix_different.pk[0]);
    $display("T|s %0d %h %h",s.tag,s.pk.a,s.pk.b);
    $display("T|alias %0d %h %h",alias_s.tag,alias_s.pk.a,alias_s.pk.b);
    $display("T|different %0d %h %h",different.tag,different.pk.a,different.pk.b);
    $display("T|typed %0d %h %h",typed.tag,typed.pk.a,typed.pk.b);
    $display("T|named %0d %h %h",named.tag,named.pk.a,named.pk.b);
    $display("T|leaf_key %0d %h",leaf_key.tag,leaf_key.pk);
    $display("T|vector %0d %h %h",vs.tag,vs.pk[7:4],vs.pk[3:0]);
    $display("T|packed_array %0d %h %h %h %h",pas.tag,pas.pk[1].a,pas.pk[1].b,pas.pk[0].a,pas.pk[0].b);
    $display("T|enum %0d %h",es.tag,es.pk);
    $display("T|many %0d %h %h %h %h",many.tag,many.x.a,many.x.b,many.y.a,many.y.b);
    $display("T|nested %0d %0d %h %h",nested.tag,nested.sub.tag,nested.sub.pk.a,nested.sub.pk.b);
    $display("T|array %h %h %h %h",arr[0].a,arr[0].b,arr[1].a,arr[1].b);
    p=8'hab;
    #1;
    $display("T|update %h %h %h %h",s.pk.a,s.pk.b,many.x.a,many.y.b);
    $finish;
  end
endmodule
